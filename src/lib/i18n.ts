export type Dict = (typeof dict)["en"];

export function useLang(): { lang: Lang; t: Dict; toggle: () => void } {
  const current = useSyncExternalStore(subscribe, getLang, getLang);
  return {
    lang: current,
    t: dict[current],
    toggle: () => setLang(current === "en" ? "th" : "en"),
  };
}
